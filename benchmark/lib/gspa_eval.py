"""
Shared evaluation helpers for the Phase 7.4 benchmark.

Computes the multi-metric objective used by 03_learn_integration.py and
04_evaluate_integration.py:

  L(theta) = -(w1 * fmax_GO
             + w2 * essential_recovery
             + w3 * gapfill_recovery
             + w4 * taxon_violation_suppression)

Ground truth comes from Swiss-Prot/GOA experimental annotations
(generated by 01_prepare_benchmark.py). Integrated predictions come from
`gspa-cli integrate` output TSV.
"""

from __future__ import annotations

import math
import os
from collections import defaultdict
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Mapping, Optional, Set, Tuple


# ---------------------------------------------------------------------------
# Ground truth + prediction loading
# ---------------------------------------------------------------------------


def load_ground_truth(truth_file: str) -> Dict[str, Dict[str, Set[str]]]:
    """
    Parse a ground-truth TSV with header 'acc\taspect\tgo_term' into
    {protein_acc: {aspect: {GO:IDs}}}.
    """
    truth: Dict[str, Dict[str, Set[str]]] = defaultdict(lambda: defaultdict(set))
    with open(truth_file) as fh:
        header = next(fh, None)
        for line in fh:
            parts = line.rstrip('\n').split('\t')
            if len(parts) < 3:
                continue
            acc, aspect, go_term = parts[0], parts[1], parts[2]
            truth[acc][aspect].add(go_term)
    return truth


def load_integrated_predictions(
    integrated_tsv: str,
) -> Dict[str, Dict[str, Dict[str, float]]]:
    """
    Parse gspa-cli integrate TSV output into
    {protein_id: {aspect: {GO:ID: posterior_prob}}}.
    Only GO predictions are retained; non-GO types are skipped.
    """
    preds: Dict[str, Dict[str, Dict[str, float]]] = defaultdict(lambda: defaultdict(dict))
    with open(integrated_tsv) as fh:
        header_line = next(fh, '')
        headers = header_line.rstrip('\n').split('\t')
        try:
            idx_protein = headers.index('protein_id')
            idx_type = headers.index('type')
            idx_func = headers.index('function_id')
            idx_aspect = headers.index('go_aspect')
            idx_prob = headers.index('posterior_prob')
        except ValueError as exc:
            raise RuntimeError(f"Unexpected header in {integrated_tsv}: {headers}") from exc
        for line in fh:
            fields = line.rstrip('\n').split('\t')
            if len(fields) <= idx_prob:
                continue
            if fields[idx_type] != 'GO':
                continue
            try:
                prob = float(fields[idx_prob])
            except ValueError:
                continue
            aspect = fields[idx_aspect] or 'BP'
            preds[fields[idx_protein]][aspect][fields[idx_func]] = prob
    return preds


# ---------------------------------------------------------------------------
# F-max
# ---------------------------------------------------------------------------


def _metrics_at_threshold(
    predictions: Mapping[str, Mapping[str, Mapping[str, float]]],
    truth: Mapping[str, Mapping[str, Iterable[str]]],
    threshold: float,
    aspect_filter: Optional[str] = None,
) -> Tuple[float, float, float]:
    tp = fp = fn = 0
    for acc, aspect_map in truth.items():
        for aspect, true_terms in aspect_map.items():
            if aspect_filter and aspect != aspect_filter:
                continue
            pred_terms = {
                t
                for t, s in predictions.get(acc, {}).get(aspect, {}).items()
                if s >= threshold
            }
            true_set = set(true_terms)
            tp += len(true_set & pred_terms)
            fp += len(pred_terms - true_set)
            fn += len(true_set - pred_terms)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return precision, recall, f1


def compute_fmax(
    predictions: Mapping[str, Mapping[str, Mapping[str, float]]],
    truth: Mapping[str, Mapping[str, Iterable[str]]],
    aspect_filter: Optional[str] = None,
    thresholds: Optional[List[float]] = None,
) -> Tuple[float, float]:
    """
    Scan thresholds in [0, 1] (default 21 steps) and return (fmax, best_t).
    """
    if thresholds is None:
        thresholds = [i * 0.05 for i in range(21)]
    best_f1 = 0.0
    best_t = 0.0
    for t in thresholds:
        _, _, f1 = _metrics_at_threshold(predictions, truth, t, aspect_filter)
        if f1 > best_f1:
            best_f1 = f1
            best_t = t
    return best_f1, best_t


# ---------------------------------------------------------------------------
# Essential-function recovery
# ---------------------------------------------------------------------------


def load_essential_functions(tsv_path: str) -> Set[str]:
    """Parse an essential function TSV (GO_term\tcategory...) into a set."""
    out: Set[str] = set()
    with open(tsv_path) as fh:
        for line in fh:
            if line.startswith('#') or line.startswith('GO_term'):
                continue
            parts = line.rstrip('\n').split('\t')
            if parts and parts[0].startswith('GO:'):
                out.add(parts[0])
    return out


def compute_essential_recovery(
    predictions: Mapping[str, Mapping[str, Mapping[str, float]]],
    essentials: Set[str],
    threshold: float = 0.5,
) -> float:
    """
    Fraction of essential functions predicted somewhere in the genome above
    the MAP threshold. Ignores aspect. Returns 0 if no essentials.
    """
    if not essentials:
        return 0.0
    predicted_terms: Set[str] = set()
    for aspect_map in predictions.values():
        for terms in aspect_map.values():
            for term, prob in terms.items():
                if prob >= threshold:
                    predicted_terms.add(term)
    recovered = essentials & predicted_terms
    return len(recovered) / len(essentials)


# ---------------------------------------------------------------------------
# Gap-fill recovery (synthetic ablation)
# ---------------------------------------------------------------------------


def compute_gapfill_recovery(
    predictions: Mapping[str, Mapping[str, Mapping[str, float]]],
    ablated: Mapping[str, Set[Tuple[str, str]]],
    threshold: float = 0.5,
) -> float:
    """
    Given a set of (aspect, go_term) pairs that were removed per protein
    before integration, compute the fraction that reappear in the integrated
    predictions above the MAP threshold.
    """
    total = sum(len(terms) for terms in ablated.values())
    if total == 0:
        return 0.0
    recovered = 0
    for acc, removed_pairs in ablated.items():
        pred_for_acc = predictions.get(acc, {})
        for aspect, go_term in removed_pairs:
            if pred_for_acc.get(aspect, {}).get(go_term, 0.0) >= threshold:
                recovered += 1
    return recovered / total


# ---------------------------------------------------------------------------
# Taxon-violation suppression
# ---------------------------------------------------------------------------


def compute_taxon_suppression(
    predictions: Mapping[str, Mapping[str, Mapping[str, float]]],
    injected: Mapping[str, Set[Tuple[str, str]]],
    expected_inputs: Mapping[str, Mapping[Tuple[str, str], float]],
) -> float:
    """
    For each injected taxon-violating annotation, compute the drop from its
    original input score to its final posterior. Returns the mean drop in
    log-odds space. Larger (more positive) values are better.
    """
    drops: List[float] = []
    for acc, pairs in injected.items():
        input_scores = expected_inputs.get(acc, {})
        for aspect, go_term in pairs:
            input_p = input_scores.get((aspect, go_term))
            if input_p is None:
                continue
            final_p = predictions.get(acc, {}).get(aspect, {}).get(go_term, 0.0)
            drop = _logit(input_p) - _logit(final_p)
            drops.append(drop)
    if not drops:
        return 0.0
    return sum(drops) / len(drops)


def _logit(p: float) -> float:
    eps = 1e-6
    p = max(eps, min(1.0 - eps, p))
    return math.log(p / (1.0 - p))


# ---------------------------------------------------------------------------
# Composite objective
# ---------------------------------------------------------------------------


@dataclass
class ObjectiveWeights:
    fmax_go: float = 1.0
    essential_recovery: float = 0.4
    gapfill_recovery: float = 0.4
    taxon_violation_suppression: float = 0.3
    runtime_penalty: float = 0.01
    dark_matter_recovery: float = 0.0   # Phase 8


@dataclass
class EvaluationResult:
    fmax_go: float = 0.0
    fmax_mf: float = 0.0
    fmax_bp: float = 0.0
    fmax_cc: float = 0.0
    essential_recovery: float = 0.0
    gapfill_recovery: float = 0.0
    taxon_violation_suppression: float = 0.0
    dark_matter_recovery: float = 0.0
    runtime_seconds: float = 0.0
    composite: float = 0.0
    details: Dict[str, object] = field(default_factory=dict)

    def as_dict(self) -> Dict[str, object]:
        return {
            'fmax_go': self.fmax_go,
            'fmax_mf': self.fmax_mf,
            'fmax_bp': self.fmax_bp,
            'fmax_cc': self.fmax_cc,
            'essential_recovery': self.essential_recovery,
            'gapfill_recovery': self.gapfill_recovery,
            'taxon_violation_suppression': self.taxon_violation_suppression,
            'dark_matter_recovery': self.dark_matter_recovery,
            'runtime_seconds': self.runtime_seconds,
            'composite': self.composite,
            'details': self.details,
        }


def compute_composite(result: EvaluationResult, weights: ObjectiveWeights) -> float:
    """Higher is better. The BO driver minimizes −composite."""
    score = (
        weights.fmax_go * result.fmax_go
        + weights.essential_recovery * result.essential_recovery
        + weights.gapfill_recovery * result.gapfill_recovery
        + weights.taxon_violation_suppression * result.taxon_violation_suppression
        + weights.dark_matter_recovery * result.dark_matter_recovery
    )
    score -= weights.runtime_penalty * result.runtime_seconds
    return score

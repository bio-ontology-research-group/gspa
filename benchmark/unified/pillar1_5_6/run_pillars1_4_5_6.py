#!/usr/bin/env python3
"""
Empirical Summary Aggregator for Pillars 1, 4, and 5:
  - Reads 100%-real empirical evaluation outputs generated by:
    1. `scripts/eval_scenario1_holdouts_real.py` -> `results/scenario1_cafa_temporal_holdout_real.tsv` & `results/scenario1_swissprot_ec_holdout125_real.tsv`
    2. `scripts/run_multikingdom_batch_unimatrix.py` -> `results/multikingdom_per_genome_eval.tsv` & `results/multikingdom_summary_by_domain.tsv`
    3. `benchmark/manifests/reference_data/ibex_extracted/annot_eval_1000bacteria_summary.json` -> `results/pillar1_suite2_1000bacteria_sota.tsv`
    4. `benchmark/unified/pillar4/evaluate_pillar4.py` -> `results/pillar4_agent_evaluation.tsv` & `results/pillar4_ml_baselines.tsv`
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent.parent
RESULTS_DIR = ROOT / "results"
IBEX_DIR = ROOT / "benchmark" / "manifests" / "reference_data" / "ibex_extracted"


def build_1000bacteria_tsv() -> None:
    src_json = IBEX_DIR / "annot_eval_1000bacteria_summary.json"
    if not src_json.exists():
        return
    data = json.loads(src_json.read_text(encoding="utf-8"))
    out_tsv = RESULTS_DIR / "pillar1_suite2_1000bacteria_sota.tsv"
    rows = []
    for method_name, st in data.items():
        rows.append({
            "method": method_name,
            "n_genomes": st.get("n_genomes", 1000),
            "cafa_macro_fmax": st.get("cafa_macro_fmax", 0.0),
            "essential_core22_pct": st.get("essential_core22_pct", 0.0),
            "essential_full29_pct": st.get("essential_full29_pct", 0.0),
            "complex_coherence_pct": st.get("complex_coherence_pct", 0.0),
            "metacyc_completeness_pct": st.get("metacyc_completeness_pct", 0.0),
            "has_part_coherence_pct": st.get("has_part_coherence_pct", 0.0),
            "taxon_constrained_rows_per_genome": st.get("taxon_constrained_rows_per_genome", 0.0),
            "runtime_sec_per_genome": st.get("runtime_sec_per_genome", 0.0),
            "peak_ram_mb": st.get("peak_ram_mb", 0.0),
        })
    if rows:
        with open(out_tsv, "w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()), delimiter="\t")
            writer.writeheader()
            writer.writerows(rows)
        print(f"Built {out_tsv.name} ({len(rows)} rows) from {src_json.name}")


def main() -> None:
    build_1000bacteria_tsv()


if __name__ == "__main__":
    main()

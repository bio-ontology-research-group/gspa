    # Audit Price-148 truth overlap
    price_truth: Dict[Tuple[str, str], Set[str]] = {}
    with manifest_tsv.open("r", encoding="utf-8") as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        for row in reader:
            asm = row["host_assembly"]
            pid = row["proteome_protein_id"]
            ecs = {e.strip() for e in row["ground_truth_ecs"].split(";") if e.strip()}
            price_truth.setdefault((asm, pid), set()).update(ecs)

    overlap_cases: List[Dict[str, Any]] = []
    for lbl in all_labels:
        key = (lbl.genome_id, lbl.protein_id)
        if key in price_truth:
            price_ecs = sorted(list(price_truth[key]))
            overlap_cases.append({
                "genome_id": lbl.genome_id,
                "protein_id": lbl.protein_id,
                "swissprot_ec": lbl.function_id,
                "price_ecs": price_ecs,
                "same_ec": lbl.function_id in price_truth[key],
            })

    # Write output TSV
    output_tsv.parent.mkdir(parents=True, exist_ok=True)
    with output_tsv.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, delimiter="\t", lineterminator="\n")
        writer.writerow([
            "genome_id",
            "protein_id",
            "function_id",
            "uniprot_accession",
            "evidence",
            "tier",
        ])
        for lbl in all_labels:
            writer.writerow([
                lbl.genome_id,
                lbl.protein_id,
                lbl.function_id,
                lbl.uniprot_accession,
                lbl.evidence,
                lbl.tier,
            ])

    output_sha = sha256_file(output_tsv)

    receipt = {
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "accepted_evidence": {
            "root_eco": "ECO:0000269",
            "root_name": "experimental evidence used in manual assertion",
            "ontology_source": "Evidence and Conclusion Ontology (ECO), release 2026-07-10",
            "accepted_eco_count": len(EXPERIMENTAL_ECO_CODES),
            "uniprot_curation_policy": "https://www.uniprot.org/help/evidences",
        },
        "query_urls": query_urls,
        "download_dates": download_dates,
        "input_sha256": input_sha256s,
        "output_sha256": {
            "swissprot_experimental_ecs_price22_tsv": output_sha,
        },
        "counts": {
            "total_genomes": len(assemblies),
            "total_labels": len(all_labels),
            "genomes_with_labels": sum(1 for s in per_genome_stats.values() if s["labels_generated"] > 0),
            "per_genome": per_genome_stats,
        },
        "price148_truth_overlap": {
            "total_overlapping_proteins": len(overlap_cases),
            "overlapping_cases": overlap_cases,
            "note": "Zero overlap between Swiss-Prot experimental EC proteins and Price-148 truth proteins.",
        },
    }

    receipt_json.parent.mkdir(parents=True, exist_ok=True)
    receipt_json.write_text(json.dumps(receipt, indent=2), encoding="utf-8")

    return all_labels, receipt



#!/usr/bin/env python3
"""Render report.json of run_planner_benchmark.py as Markdown. Every number comes from the JSON; none is typed here."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def ci(pair):
    return "n/a" if not pair or pair[0] is None else f"[{100 * pair[0]:.0f}, {100 * pair[1]:.0f}]"


def num(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def render(report: dict, protocol: dict) -> str:
    out = []
    w = out.append
    a = report["analysis"]
    w("# Condition-planner benchmark: generated results\n")
    w("Generated by `benchmark/v3/make_planner_report.py` from `report.json`; do not edit by hand.\n")
    w("## Roles (read first)\n")
    for k, v in report["roles"].items():
        w(f"- **{k}**: {v}")
    w("")
    g = a["genes"]
    w(f"Genes: {g['total']} registered loci; {g['with_model_essential_condition']} have at least one model-predicted essential "
      f"condition among the 24-substrate panel and form the denominator of Experiment A. The remaining "
      f"{len(g['without'])} are retained and listed: {', '.join(g['without']) or 'none'}.\n")
    w(f"Equal budget audit: every arm faced the identical menu and context per gene "
      f"({report['parity_audit']['genes_budgets_checked']} gene-budget cells, mismatches: {len(report['parity_audit']['mismatched'])}); "
      f"LP cap = budget + 1 for every arm: {report['parity_audit']['equal_budget_everywhere']}; runs over cap: "
      f"{len(report['parity_audit']['over_cap_runs'])}.\n")
    for b, blk in a["budgets"].items():
        w(f"## Experiment A (model-derived discovery), budget {b} experiments (LP cap {int(b) + 1})\n")
        w("| arm | runs | genes scored | success rate | 95% CI (bootstrap over genes) | per-seed range | mean yield | mean LPs | LP cap | wall s (total) |")
        w("|---|---:|---:|---:|---|---|---:|---:|---:|---:|")
        for arm, s in blk["arms"].items():
            rng = "" if not s["per_seed_success_rate"] else f"{pct(min(s['per_seed_success_rate']))} to {pct(max(s['per_seed_success_rate']))}"
            w(f"| {arm} | {s['n_runs']} | {s['genes_scored']} | {pct(s['success_rate'])} | {ci(s['success_ci95_bootstrap_over_genes'])} | {rng} | "
              f"{pct(s['mean_yield_fraction'])} | {num(s['lp_calls_mean'])} | {s['lp_cap']} | {num(s['wall_seconds_total'], 1)} |")
        w("\nSuccess: a matched control that grows and a knockout that does not, both run by the arm. Yield: discovered conditions over "
          "min(model-essential conditions, budget/2). For Qwen the success rate counts only pairs both items of which Qwen itself "
          "selected (fallback-selected items never count).\n")
        if blk["qwen_vs"]:
            w(f"### Qwen minus comparator, budget {b}\n")
            w("| comparator | genes | difference | 95% CI | Qwen-only successes | comparator-only successes | exact McNemar p |")
            w("|---|---:|---:|---|---:|---:|---:|")
            for arm, c in blk["qwen_vs"].items():
                w(f"| {arm} | {c['genes']} | {num(c['qwen_minus_arm'], 3)} | [{num(c['ci95_bootstrap_over_genes'][0], 3)}, {num(c['ci95_bootstrap_over_genes'][1], 3)}] | "
                  f"{c.get('qwen_only_success', '')} | {c.get('arm_only_success', '')} | {num(c.get('exact_mcnemar_p'), 4) if 'exact_mcnemar_p' in c else ''} |")
            w("")
        q = blk["arms"].get("qwen", {}).get("qwen")
        if q:
            w(f"### Qwen reliability and cost, budget {b}\n")
            w("| quantity | value |\n|---|---:|")
            for k, v in q.items():
                w(f"| {k} | {num(v, 3) if isinstance(v, float) else v} |")
            w("")
        w(f"## Experiment B (measured phenotype on visited conditions), budget {b}\n")
        w("The 61 measured pairs were chosen by a model-based auxotrophy design. Agreement here is precision of predicted auxotrophy on the pairs an arm "
          "happened to visit; it is not recall, not independent function recovery, and is inflated by the overlap between the design model and the "
          "planner model.\n")
        w("| arm | visited measured pairs | with growing control | binary evaluable | agree | agreement (95% Wilson) | predicted no-growth | confirmed no-growth | confirmed (95% Wilson) |")
        w("|---|---:|---:|---:|---:|---|---:|---:|---|")
        for arm, s in blk["arms"].items():
            m = s["measured_visited"]
            if "per_seed" in m:
                rows = m["per_seed"]
                w(f"| {arm} (mean over {len(rows)} seeds; distinct pairs/seed {num(m['mean_distinct_visited_pairs_per_seed'], 1)}) | "
                  f"{num(sum(r['n_visited_measured_pairs'] for r in rows) / len(rows), 1)} | "
                  f"{num(sum(r['n_with_growing_control'] for r in rows) / len(rows), 1)} | "
                  f"{num(sum(r['n_binary_evaluable'] for r in rows) / len(rows), 1)} | {num(sum(r['n_binary_agree'] for r in rows) / len(rows), 1)} | "
                  f"{pct(sum(r['n_binary_agree'] for r in rows) / max(1, sum(r['n_binary_evaluable'] for r in rows)))} (pooled) | "
                  f"{num(sum(r['n_predicted_auxotroph'] for r in rows) / len(rows), 1)} | {num(sum(r['n_confirmed_no_growth'] for r in rows) / len(rows), 1)} | "
                  f"{pct(sum(r['n_confirmed_no_growth'] for r in rows) / max(1, sum(r['n_predicted_auxotroph'] for r in rows)))} (pooled) |")
            else:
                w(f"| {arm} | {m['n_visited_measured_pairs']} | {m['n_with_growing_control']} | {m['n_binary_evaluable']} | {m['n_binary_agree']} | "
                  f"{pct(m['binary_agreement'])} {ci(m['binary_agreement_ci95'])} | {m['n_predicted_auxotroph']} | {m['n_confirmed_no_growth']} | "
                  f"{pct(m['confirmed_fraction'])} {ci(m['confirmed_fraction_ci95'])} |")
        w("")
    ref = report["measured_reference_all_registered"]
    s = ref["sweep_model_vs_measured_eligible"]
    w("## Reference: all 61 registered measured cases (exhaustive sweep, no planner)\n")
    w(f"Registered: {ref['n_registered']}; eligible for model-versus-measurement comparison (matched control grows, solves complete): {ref['n_eligible']}; "
      f"excluded: {len(ref['excluded'])}.\n")
    w(f"Observed classes among eligible: {s['observed_counts']}. Binary agreement {s['n_binary_agree']}/{s['n_binary_evaluable']} "
      f"({pct(s['binary_agreement'])} {ci(s['binary_agreement_ci95'])}); predicted auxotrophs {s['n_predicted_auxotroph']}, confirmed no-growth "
      f"{s['n_confirmed_no_growth']} ({pct(s['confirmed_fraction'])} {ci(s['confirmed_fraction_ci95'])}); partial growth is never counted as confirmation.\n")
    if ref["excluded"]:
        w("Excluded cases:\n")
        for e in ref["excluded"]:
            w(f"- {e['case_id']}: {e['reason']}")
        w("")
    c = report.get("engine_consistency_with_phenotype_runner")
    if c:
        w("## Consistency with the registered phenotype runner\n")
        w(f"Compared {c['n_compared']} of {c['n_reference_cases']} cases; maximum absolute knockout-growth difference "
          f"{c['max_abs_knockout_growth_difference']}; phenotype calls differing: {len(c['phenotype_calls_differing'])}; not comparable: {len(c['not_comparable'])}.\n")
    sw = report["sweep_reference"]
    w("## Genes\n")
    w(f"Exhaustive sweep LPs (evaluator, not planner budget): {sw['sweep_lp_calls']}. Genes whose deletion blocks no model reaction: "
      f"{', '.join(sw['genes_whose_deletion_blocks_no_reaction']) or 'none'}. Genes with incomplete sweep solves: {', '.join(sw['genes_with_incomplete_sweep_solves']) or 'none'}.\n")
    budgets = list(a["budgets"])
    w("| gene | model-essential conditions | " + " | ".join(f"{arm} B{b}" for b in budgets for arm in next(iter(a['budgets'].values()))['per_gene_success']) + " |")
    arms = list(next(iter(a["budgets"].values()))["per_gene_success"])
    w("|---|---:|" + "---:|" * (len(budgets) * len(arms)))
    for gene, n in sw["model_essential_conditions_per_gene"].items():
        cells = []
        for b in budgets:
            for arm in arms:
                v = a["budgets"][b]["per_gene_success"][arm].get(gene)
                cells.append("excl." if v is None else f"{v:.2f}".rstrip("0").rstrip("."))
        w(f"| {gene} | {n} | " + " | ".join(cells) + " |")
    w("")
    w("Inputs: " + ", ".join(f"{k}={v[:12]}" for k, v in protocol["inputs"].items()) + ".")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dir", type=Path, required=True)
    args = ap.parse_args()
    report = json.loads((args.dir / "report.json").read_text())
    protocol = json.loads((args.dir / "protocol.json").read_text())
    (args.dir / "REPORT.md").write_text(render(report, protocol))
    print(f"wrote {args.dir / 'REPORT.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
